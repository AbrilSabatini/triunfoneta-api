export async function seedMatches(repo: Repository<Match>): Promise<Match[]> {
  const result: Match[] = [];

  for (const data of MATCHES_DATA) {
    const existing = await repo.findOne({
      where: { homeTeam: data.homeTeam, awayTeam: data.awayTeam },
    });

    if (existing) {
      console.log(
        `  ⏭️  Partido ya existe: ${data.homeTeam} vs ${data.awayTeam}`,
      );
      result.push(existing);
      continue;
    }

    const match = repo.create({
      homeTeam: data.homeTeam,
      awayTeam: data.awayTeam,
      matchDate: new Date(data.matchDate),
      picksCloseAt: new Date(data.picksCloseAt),
      stage: data.stage,
      group: data.group,
      scoreHome: null,
      scoreAway: null,
      isFinished: false,
      pointsProcessed: false,
    });

    const saved = await repo.save(match);
    result.push(saved);
  }

  return result;
}
